#!/usr/bin/env python3
"""Regenerate the SEO block in every Learnings page, plus sitemap.xml and robots.txt.

Run from the repo root after adding or renaming a page, or changing a page's <h1> or lead paragraph:

    python3 tools/update_seo.py

Each page gets one generated block in its <head>, between the "seo:start" and "seo:end" comments:
title, description, canonical URL, Open Graph / Twitter tags, favicon link and JSON-LD. Everything is
derived from the page itself (its <h1> and its <p class="lead">), so edit those, not the block.
The script is safe to run repeatedly. It only touches index.html, archive.html and learnings/*/docs/*.html.
"""
import datetime
import glob
import html
import json
import os
import re
import subprocess

SITE = "https://hygull.github.io/"
AUTHOR = "Rishikesh Agrawani"
SITE_NAME = "Learnings by Rishikesh Agrawani"
IMAGE = "https://avatars.githubusercontent.com/u/23253178?v=4"
SAME_AS = [
    "https://github.com/hygull",
    "https://www.linkedin.com/in/rishikesh-agrawani-0358ba119/",
    "https://stackoverflow.com/users/6615163/hygull",
    "https://x.com/hygull",
    "https://www.instagram.com/hygull/",
    "https://www.facebook.com/rishikesh.agrawani",
    "https://open.spotify.com/artist/2ocvkFVNkJXmbkgpReOxtC",
]
HOME_TITLE = "Rishikesh Agrawani (hygull) | Python and System Design Tutorials"
CAREER_START = datetime.date(2016, 6, 9)   # "N+ years of experience" is counted from this day
HOME_DESC = ("Rishikesh Agrawani (hygull), backend engineer with {years}+ years of experience. Free tutorials with "
             "runnable code: system design interviews, Python, React, Next.js and Bash.")
ARCHIVE_DESC = ("Older work by Rishikesh Agrawani: the Pythofrank Python tutorial site from 2017, JavaScript demos, "
                "an image gallery, lyrics and experiments.")
FOLDER_GROUP = {
    "React": ("React to Next", "frontend"), "Next": ("React to Next", "frontend"),
    "Next_React": ("React to Next", "frontend"), "Design": ("React to Next", "frontend"),
    "SystemDesign": ("System Design", "system-design"), "Bash": ("Bash", "bash"),
}
START, END = "<!-- seo:start (generated by tools/update_seo.py, do not edit by hand) -->", "<!-- seo:end -->"


def years_of_experience(today=None):
    today = today or datetime.date.today()
    years = today.year - CAREER_START.year
    if (today.month, today.day) < (CAREER_START.month, CAREER_START.day):
        years -= 1
    return years


def text(fragment):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", fragment))).strip()


def shorten(sentence, limit=158):
    if len(sentence) <= limit:
        return sentence
    cut = sentence[:limit]
    stop = max(cut.rfind(". "), cut.rfind("? "))
    if stop > 80:
        return cut[:stop + 1]
    return cut[:cut.rfind(" ")].rstrip(",;:") + "..."


def last_modified(path):
    dirty = subprocess.run(["git", "status", "--porcelain", "--", path], capture_output=True, text=True).stdout.strip()
    if not dirty:
        day = subprocess.run(["git", "log", "-1", "--format=%cs", "--", path], capture_output=True, text=True).stdout.strip()
        if day:
            return day
    return datetime.date.today().isoformat()


def describe(path, source):
    """Return (title, description, breadcrumb list of (name, url), schema type)."""
    body = re.sub(r"<script.*?</script>", "", source, flags=re.S)
    if path == "index.html":
        return HOME_TITLE, HOME_DESC.format(years=years_of_experience()), [], "home"
    if path == "archive.html":
        return "Archive | " + AUTHOR, ARCHIVE_DESC, [("Archive", SITE + "archive.html")], "page"
    h1 = text(re.search(r"<h1>(.*?)</h1>", body, re.S).group(1))
    lead = re.search(r'<p class="lead">(.*?)</p>', body, re.S)
    desc = shorten(text(lead.group(1))) if lead else h1
    folder = path.split("/")[1]
    if folder == "Python":
        current = re.search(r'<a href="[^"]*#([a-z-]+)" aria-current="true">(.*?)</a>', body)
        group = (text(current.group(2)), current.group(1))
    else:
        group = FOLDER_GROUP[folder]
    name = h1
    if folder == "SystemDesign" and "system design" not in h1.lower():
        name = h1 + " - System Design"
    crumbs = [(group[0], SITE + "#" + group[1]), (h1, SITE + path)]
    return name + " | " + AUTHOR, desc, crumbs, "article"


def block(path, source):
    title, desc, crumbs, kind = describe(path, source)
    url = SITE if path == "index.html" else SITE + path
    up = "../" * path.count("/")
    person = {"@type": "Person", "name": AUTHOR, "url": SITE}
    graph = []
    if kind == "home":
        graph.append({"@type": "Person", "@id": SITE + "#me", "name": AUTHOR, "alternateName": "hygull", "url": SITE,
                      "image": IMAGE, "jobTitle": "Backend Engineer",
                      "knowsAbout": ["Python", "System design", "Backend development", "Distributed systems"],
                      "sameAs": SAME_AS})
        graph.append({"@type": "WebSite", "@id": SITE + "#site", "name": SITE_NAME, "url": SITE,
                      "description": desc, "inLanguage": "en", "author": {"@id": SITE + "#me"}})
    else:
        if kind == "article":
            graph.append({"@type": "TechArticle", "headline": crumbs[-1][0], "description": desc, "url": url,
                          "mainEntityOfPage": url, "inLanguage": "en", "image": IMAGE, "author": person,
                          "publisher": person, "dateModified": last_modified(path),
                          "isPartOf": {"@type": "WebSite", "name": SITE_NAME, "url": SITE}})
        items = [("Home", SITE)] + crumbs
        graph.append({"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": i, "name": n, "item": u} for i, (n, u) in enumerate(items, 1)]})
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, indent=1).replace("</", "<\\/")
    esc = lambda value: html.escape(value, quote=True)
    lines = [
        START,
        "<title>%s</title>" % html.escape(title, quote=False),
        '<meta name="description" content="%s">' % esc(desc),
        '<meta name="author" content="%s">' % AUTHOR,
        '<link rel="canonical" href="%s">' % url,
        '<link rel="icon" href="%sfavicon.svg" type="image/svg+xml">' % up,
        '<meta property="og:site_name" content="%s">' % SITE_NAME,
        '<meta property="og:type" content="%s">' % ("website" if kind != "article" else "article"),
        '<meta property="og:title" content="%s">' % esc(title),
        '<meta property="og:description" content="%s">' % esc(desc),
        '<meta property="og:url" content="%s">' % url,
        '<meta property="og:image" content="%s">' % IMAGE,
        '<meta name="twitter:card" content="summary">',
        '<meta name="twitter:title" content="%s">' % esc(title),
        '<meta name="twitter:description" content="%s">' % esc(desc),
        '<script type="application/ld+json">',
        data,
        "</script>",
        END,
    ]
    return "\n".join(lines) + "\n"


def update(path):
    source = open(path, encoding="utf-8").read()
    # the visible figure is recomputed in the browser by tutorial.js; keep the HTML fallback current too
    source_before = source
    source = re.sub(r'(<span data-years-since="%s">)\d+(</span>)' % CAREER_START.isoformat(),
                    r"\g<1>%d\g<2>" % years_of_experience(), source)
    head_end = source.index("</head>")
    head, rest = source[:head_end], source[head_end:]
    head = re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n", "", head, flags=re.S)
    head = re.sub(r"<title>.*?</title>\n", "", head, flags=re.S)
    head = re.sub(r'<meta (?:name="(?:description|author)"|property="og:[a-z_]+"|name="twitter:[a-z]+")[^>]*>\n', "", head)
    viewport = re.search(r'<meta name="viewport"[^>]*>\n', head)
    at = viewport.end()
    new = head[:at] + block(path, source) + head[at:] + rest
    if new != source_before:
        open(path, "w", encoding="utf-8").write(new)
        return True
    return False


def main():
    pages = ["index.html", "archive.html"] + sorted(glob.glob("learnings/*/docs/*.html"))
    changed = sum(update(p) for p in pages)
    entries = []
    for p in pages:
        loc = SITE if p == "index.html" else SITE + p
        priority = "1.0" if p == "index.html" else ("0.3" if p == "archive.html" else "0.8")
        entries.append("  <url><loc>%s</loc><lastmod>%s</lastmod><priority>%s</priority></url>" % (loc, last_modified(p), priority))
    open("sitemap.xml", "w", encoding="utf-8").write(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(entries) + "\n</urlset>\n")
    open("robots.txt", "w", encoding="utf-8").write("User-agent: *\nAllow: /\n\nSitemap: %ssitemap.xml\n" % SITE)
    print("%d pages, %d changed; sitemap.xml and robots.txt written" % (len(pages), changed))


if __name__ == "__main__":
    main()
